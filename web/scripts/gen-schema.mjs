// Generate zod schemas from the worker's JSON Schemas (../schema), so the page parses
// exactly what the worker writes. CI runs this and fails if the output changes.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { jsonSchemaToZod } from 'json-schema-to-zod'

const deref = (node, defs) => {
  if (Array.isArray(node)) return node.map((n) => deref(n, defs))
  if (node && typeof node === 'object') {
    if (node.$ref) return deref(defs[node.$ref.split('/').pop()], defs)
    const out = {}
    for (const [k, v] of Object.entries(node)) if (k !== '$defs') out[k] = deref(v, defs)
    return out
  }
  return node
}

mkdirSync('lib/generated', { recursive: true })
for (const [file, name, type] of [
  ['bundle', 'bundleSchema', 'Bundle'],
  ['report', 'reportSchema', 'Report'],
  ['vrp', 'vrpSchema', 'Vrp'],
]) {
  const schema = JSON.parse(readFileSync(`../schema/${file}.schema.json`, 'utf8'))
  const code = jsonSchemaToZod(deref(schema, schema.$defs ?? {}), {
    name, type, module: 'esm', depth: 50, zodVersion: 4,
  })
  writeFileSync(`lib/generated/${file}.ts`, `// Generated by scripts/gen-schema.mjs from schema/${file}.schema.json. Do not edit.\n${code}\n`)
  console.log(`wrote lib/generated/${file}.ts`)
}
